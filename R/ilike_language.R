# The ilike language in the R binding (dev/ilike-language.md; dev/plan.md
# 3.14, I3b). The parser and the lowering are in C++ (shared by the bindings);
# here the user's C++ functions are compiled (through the same code
# generation and cache as the old format) and put into the recipe.

# TRUE if x is the placeholder of a user function, {ilike_function, role}
is_function_placeholder <- function(x)
{
  is.list(x) && !is.null(names(x)) && identical(sort(names(x)), c("ilike_function", "role"))
}

# The placeholders of a list (recursively), as a list of (function, role)
collect_placeholders <- function(x, found = list())
{
  if (is_function_placeholder(x))
    return(c(found, list(x)))
  if (is.list(x))
    for (item in x)
      found = collect_placeholders(item, found)
  found
}

# Roles of functions the language generates itself (return type, arguments):
# the plates of model statements (src/plate_likelihood_estimator.h, I4b)
internal_roles <- list(
  mfds_simulate = c("Data", "RandomNumberGenerator &rng, const Parameters &parameters"),
  mfds_prior = c("Data", ""),
  mfds_transform = c("Parameters", "const Parameters &parameters"),
  plate_structure = c("Data", "const Data &data"),
  plate_term = c("double", "const Parameters &parameters, const Data &data, const arma::mat &terms, size_t term"),
  plate_gradients = c("void", "const std::vector<std::string> &variables, std::vector<arma::mat> &gradients, const Parameters &parameters, const Data &data"),
  plate_value_gradients = c("double", "const std::vector<std::string> &variables, std::vector<arma::mat> &gradients, const Parameters &parameters, const Data &data"),
  # the simulators of unnormalised distributions (dev/plan.md 3.20, S3)
  unnormalised_sweep = c("void", "RandomNumberGenerator &rng, Parameters &parameters, const Data &data"),
  unnormalised_exact = c("Parameters", "RandomNumberGenerator &rng, const Parameters &parameters, const Data &data"),
  unnormalised_potential = c("double", "const arma::mat &field, const Parameters &parameters, const Data &data"))

# The getter's name for a function used in a role
placeholder_getter <- function(function_name, role)
{
  paste(function_name, role, "getXPtr", sep = "_")
}

# Replace the placeholders of a list by the compiled functions (pointers from
# the getters); where the role's signature has several forms, set the
# parent's "type" to the form, as the old format does.
replace_placeholders <- function(x, types, foreign_getters = list())
{
  if (!is.list(x))
    return(x)
  if (length(x) > 0)
  {
    for (k in seq_along(x))
    {
      item = x[[k]]
      if (is_function_placeholder(item))
      {
        getter = placeholder_getter(item$ilike_function, item$role)
        x[[k]] = get(getter)()
        type = types[[getter]]
        if (!is.null(type) && type != 0)
          x[["type"]] = type
      }
      else if (is_foreign_placeholder(item) || is_finite_difference_placeholder(item))
      {
        wrapper = foreign_getters[[if (is_foreign_placeholder(item)) foreign_key(item) else finite_difference_key(item)]]
        x[[k]] = get(wrapper$getter)()
        if (!is.null(wrapper$type) && wrapper$type != 0)
          x[["type"]] = wrapper$type
      }
      else if (is.list(item))
        x[[k]] = replace_placeholders(item, types, foreign_getters)
    }
  }
  x
}

# compile() for files in the ilike language
compile_ilike_language <- function(filenames, texts, keep_temporary_recipe_code = FALSE, model_parameter_list = list(),
                                   external_packages = c(), julia_bin_dir = "", julia_required_libraries = c())
{
  # (named values given for constants: what must be known when compiling,
  # such as the elements of moves on elements, uses them)
  given_constants = model_parameter_list[names(model_parameter_list) != ""]
  lowered = ilike_language_lower(texts, filenames, if (length(given_constants) > 0) given_constants else NULL)
  # (notes from the lowering: gradients by finite differences, dev/plan.md 3.10)
  for (note in unlist(lowered$notes))
    message(note)
  code_for_signatures = paste(lowered$user_code, lowered$generated_code, sep = "\n")
  # (internal, for tests and as a way out: options(ilike.plate_factors = FALSE)
  # evaluates factors from model statements whole, as in I4a)
  if (!isTRUE(getOption("ilike.plate_factors", TRUE)) && is.list(lowered$recipe$factor))
    for (k in seq_along(lowered$recipe$factor))
      if (is.list(lowered$recipe$factor[[k]]))
        lowered$recipe$factor[[k]]$plate = NULL
  # (internal, for tests: options(ilike.in_place_moves = FALSE) makes scans of
  # moves on elements through proposed particles, as in I4c-1)
  if (!isTRUE(getOption("ilike.in_place_moves", TRUE)))
    lowered$recipe$in_place_moves = FALSE

  # functions in other languages (I5): their code loaded into R (Python
  # through reticulate, Julia through JuliaCall), and the C++ wrappers that
  # call them generated by the old format's code for R expressions
  load_foreign_code(lowered, julia_bin_dir, julia_required_libraries)
  constants = lowered$constants
  if (is.null(constants)) constants = list()
  given = names(model_parameter_list)
  if (length(model_parameter_list) > 0 && (is.null(given) || all(given == "")) &&
      length(lowered$declared_constants) > 0 && all(grepl("^p[0-9]+$", lowered$declared_constants)))
    names(model_parameter_list) = paste("p", seq_along(model_parameter_list), sep = "")
  for (name in names(model_parameter_list))
    if (name != "")
      constants[[name]] = model_parameter_list[[name]]
  foreign = generate_foreign_wrappers(list(lowered$recipe, lowered$algorithms), constants,
                                      lowered$declared_constants, external_packages, julia_bin_dir, julia_required_libraries)

  # the constants whose values are fixed now, when compiling (those used in
  # model statements, in moves on elements and in calls to other languages),
  # kept with the recipe so that a run given another value can refuse it
  # (prepare_recipe) rather than silently use the compiled one
  fixed_names = unique(c(lowered$model_constants, lowered$element_constants))
  for (p in collect_foreign_placeholders(list(lowered$recipe, lowered$algorithms)))
    fixed_names = union(fixed_names, intersect(all.vars(parse(text = p$expression)), lowered$declared_constants))
  compiled_constants = constants[intersect(fixed_names, names(constants))]

  # constants used in model statements: C++ definitions with their values
  # (known when compiling, as for calls to other languages)
  constant_code = character(0)
  for (name in lowered$model_constants)
  {
    if (is.null(constants[[name]]))
      stop(paste("The constant ", name, " is used in the model statements, so its value is needed when compiling: ",
                 "give it a default in the constants section or pass it to compile(model_parameter_list = list(...)).", sep = ""),
           call. = FALSE)
    value = as.matrix(constants[[name]])
    if (!is.numeric(value))
      stop(paste("The constant ", name, " used in the model statements is not numeric.", sep = ""), call. = FALSE)
    constant_code = c(constant_code,
                      paste("static arma::mat ilike_constant_", name, "_make()", sep = ""), "{",
                      paste("  arma::mat value(", nrow(value), ", ", ncol(value), ");", sep = ""),
                      paste("  value(", seq_along(value) - 1, ") = ", format(as.vector(value), digits = 17), ";", sep = ""),
                      "  return value;", "}",
                      paste("static const arma::mat ilike_constant_", name, " = ilike_constant_", name, "_make();", sep = ""), "")
  }

  # the getters of the functions used, with their signatures checked against
  # their roles (the same rules as the old format's blocks)
  placeholders = collect_placeholders(list(lowered$recipe, lowered$algorithms))
  getters = character(0)
  types = list()
  done = character(0)
  for (p in placeholders)
  {
    getter = placeholder_getter(p$ilike_function, p$role)
    if (getter %in% done)
      next
    done = c(done, getter)
    signature = ilike_find_cpp_function_signature(code_for_signatures, p$ilike_function)
    if (signature == "")
      stop(paste("The C++ function ", p$ilike_function, " is not defined.", sep = ""))
    # functions generated for model statements' plates (I4b): fixed signatures
    internal = internal_roles[[p$role]]
    if (!is.null(internal))
    {
      types[[getter]] = 0
      getters = c(getters,
                  "// [[Rcpp::export]]",
                  paste("SEXP ", getter, "() {", sep = ""),
                  paste("  typedef", internal[1], "(*funcPtr)(", internal[2], ");"),
                  paste("  return XPtr<funcPtr>(new funcPtr(&", p$ilike_function, "));"),
                  "}",
                  "")
      next
    }
    # (the old format's checks; their messages are given for the function)
    rt = tryCatch({
      pt = parameter_types_for_cpp(signature)
      rt = return_types_for_cpp(p$role, 0, pt[[1]], pt[[2]], pt[[3]], pt[[4]])
      check_cpp_function_signature(signature, rt[[2]], p$role, 0, p$ilike_function)
      rt
    }, error = function(e) {
      message = sub("^Block [^,]*, line number [0-9]*: ", "", conditionMessage(e))
      message = sub("^function [A-Za-z_0-9]* has", "it has", message)
      stop(paste("cpp::", p$ilike_function, " (used as ", p$role, "): ", message, sep = ""), call. = FALSE)
    })
    types[[getter]] = rt[[4]]
    getters = c(getters,
                "// [[Rcpp::export]]",
                paste("SEXP ", getter, "() {", sep = ""),
                paste("  typedef", rt[[1]], "(*funcPtr)(", rt[[2]], ");"),
                paste("  return XPtr<funcPtr>(new funcPtr(&", p$ilike_function, "));"),
                "}",
                "")
  }

  if (length(getters) > 0 || length(foreign$code) > 0)
  {
    sets_file = grepl("ilike_model_file()", lowered$generated_code, fixed = TRUE)
    model_for_compilation_name = tempfile(pattern = "ilike_language_", fileext = ".cpp")
    if (!keep_temporary_recipe_code)
      on.exit(unlink(model_for_compilation_name), add = TRUE)
    else
      message("Generated C++ code: ", model_for_compilation_name)
    writeLines(c('// [[Rcpp::depends(RcppArmadillo)]]',
                 '// [[Rcpp::depends(ilike)]]',
                 '// [[Rcpp::depends(BH)]]',
                 '// [[Rcpp::depends(dqrng)]]',
                 '// [[Rcpp::depends(sitmo)]]',
                 '#include <RcppArmadillo.h>',
                 '',
                 'using namespace Rcpp;',
                 '#include <ilike.h>',
                 # (log densities written as templates on the number type,
                 # for gradient = autodiff: dev/plan.md 3.10 stage 2)
                 if (grepl("ParametersT", lowered$user_code, fixed = TRUE)) '#include <ilike_autodiff.h>' else character(0),
                 'using namespace ilike;',
                 '',
                 lowered$user_code,
                 '',
                 constant_code,
                 lowered$generated_code,
                 if (sets_file) c('', '// [[Rcpp::export]]', 'void ilike_model_set_file(std::string file) { ilike_model_file() = file; }') else character(0),
                 '',
                 getters,
                 '',
                 foreign$code),
               model_for_compilation_name)
    source_generated_cpp(model_for_compilation_name, filenames)
    # the file named in the generated code's messages (C208: kept out of the
    # code, so that the compile cache does not depend on the path)
    if (sets_file)
      get("ilike_model_set_file", envir = globalenv())(lowered$element_file)
  }

  recipe = resolve_modules(replace_placeholders(lowered$recipe, types, foreign$getters))
  recipe$algorithms = replace_placeholders(lowered$algorithms, types, foreign$getters)
  recipe$constants = lowered$constants
  recipe$declared_constants = lowered$declared_constants
  recipe$compiled_constants = compiled_constants
  recipe$language = "ilike"
  recipe$uses_r_functions = isTRUE(lowered$uses_foreign)
  recipe
}

# For a recipe in the ilike language: the algorithm to run (its moves and
# settings put into the recipe as the engine reads them), and the run-time
# constants with the file's defaults filled in. Old-format recipes pass
# through (they hold their algorithm settings directly).
prepare_recipe <- function(recipe, algorithm, model_parameter_list, transform_allowed = FALSE)
{
  if (!identical(recipe$language, "ilike"))
  {
    if (!is.null(algorithm))
      stop("algorithm: only recipes in the ilike language have named algorithms.")
    return(list(recipe = recipe, model_parameter_list = model_parameter_list, settings = list()))
  }

  available = names(recipe$algorithms)
  if (is.null(algorithm))
  {
    if (length(available) > 1)
      stop(paste("The recipe has several algorithms (", paste(available, collapse = ", "),
                 "): choose one with algorithm = \"...\".", sep = ""))
    algorithm = if (length(available) == 1) available else NULL
  }
  else if (!(algorithm %in% available))
  {
    stop(paste("The recipe has no algorithm called ", algorithm, " (algorithms: ",
               if (length(available) == 0) "none" else paste(available, collapse = ", "), ").", sep = ""))
  }

  prepared = recipe
  prepared$algorithms = NULL
  # (the engine expects this entry, empty when there are no moves)
  prepared["order_of_mcmc"] = list(NULL)
  settings = list()
  if (!is.null(algorithm))
  {
    chosen = recipe$algorithms[[algorithm]]
    settings = chosen$settings
    if (is.null(settings))
      settings = list()
    chosen$settings = NULL
    for (key in names(chosen))
    {
      # the model's settings (the time index of a state-space model) and the
      # algorithm's are both method entries
      if (key == "method" && !is.null(prepared$method))
        prepared$method = c(prepared$method, chosen$method)
      else
        prepared[key] = list(chosen[[key]]) # ([[<- with NULL would remove the entry)
    }
  }

  # constants: the file's defaults, overridden by those given at run time
  constants = recipe$constants
  if (length(model_parameter_list) > 0)
  {
    given = names(model_parameter_list)
    if (is.null(given) || any(given == ""))
    {
      # a converted old file declares p1, p2, ...: an unnamed list is matched
      # to them in order, as in the old format
      declared = recipe$declared_constants
      if ((is.null(given) || all(given == "")) && length(declared) > 0 && all(grepl("^p[0-9]+$", declared)))
      {
        given = paste("p", seq_along(model_parameter_list), sep = "")
        names(model_parameter_list) = given
      }
      else
        stop("For a recipe in the ilike language, the run-time constants are given by name (model_parameter_list = list(name = value, ...)).")
    }
    for (name in given)
    {
      # a constant fixed when compiling cannot take another value now
      fixed = recipe$compiled_constants[[name]]
      if (!is.null(fixed) && !same_constant_value(fixed, model_parameter_list[[name]]))
        stop(paste("The constant ", name, " was fixed when the recipe was compiled (it is used in model statements, ",
                   "moves on elements or calls to other languages), so it cannot be given another value when running: ",
                   "compile again with compile(..., model_parameter_list = list(", name, " = ...)).", sep = ""),
             call. = FALSE)
      constants[[name]] = model_parameter_list[[name]]
    }
  }
  if (is.null(constants))
    constants = list()
  # transform = auto (or a list) in an algorithm section: for IENKI (and MFDS,
  # which says why it cannot use one); MCMC and SMC moves take their own (C209)
  if (!transform_allowed && !is.null(prepared$algorithm_transform))
    stop("transform = ... in an algorithm section is for IENKI; for MCMC and SMC, give it to each move ",
         "(e.g. move m = metropolis(norm_rw(sigma, 0.5), transform = auto)).", call. = FALSE)
  list(recipe = prepared, model_parameter_list = constants, settings = settings)
}

# Whether a constant's value given when running is the value it was compiled with
same_constant_value <- function(compiled, given)
{
  if (is.numeric(compiled) && is.numeric(given))
    return(length(compiled) == length(given) && NROW(compiled) == NROW(given) &&
           all(as.numeric(compiled) == as.numeric(given)))
  identical(compiled, given)
}

# The names a run-time setting may have: the R argument's name, or its short
# form (number_of_particles: particles; smc_iterations_to_store:
# iterations_to_store) (dev/ilike-language.md 4.7)
setting_aliases <- function(name)
{
  unique(c(name, sub("^number_of_", "", name), sub("^[a-z]+_iterations_to_store$", "iterations_to_store", name)))
}

# The arguments of an algorithm function that a file may set
settable_arguments <- function(formal_names)
{
  setdiff(formal_names, c("recipe", "results_name", "results_path", "model_parameter_list", "algorithm_parameter_list",
                          "external_packages", "julia_bin_dir", "julia_required_libraries",
                          "verify_cpp_function_types", "keep_temporary_recipe_code", "algorithm"))
}

# Run-time settings from the chosen algorithm section: each sets the
# argument of the same name (or short name), unless it was given in the call
# (dev/ilike-language.md 4.7). given: the names of the arguments in the call;
# env: the calling function's environment; formal_names: its arguments.
apply_algorithm_settings <- function(settings, given, env, formal_names)
{
  if (length(settings) == 0)
    return(invisible(NULL))
  settable = settable_arguments(formal_names)
  for (key in names(settings))
  {
    target = NULL
    for (f in settable)
      if (key %in% setting_aliases(f))
        target = f
    if (is.null(target))
      stop(paste("The setting ", key, " in the algorithm section is not a setting of this algorithm (settings: ",
                 paste(sapply(settable, function(f) setting_aliases(f)[length(setting_aliases(f))]), collapse = ", "),
                 ").", sep = ""), call. = FALSE)
    if (!(target %in% given))
      assign(target, settings[[key]], envir = env)
  }
  invisible(NULL)
}

is_module_placeholder <- function(x)
{
  is.list(x) && !is.null(names(x)) && ("ilike_module" %in% names(x))
}

# The algorithmic likelihoods of a recipe: each imported file is compiled
# (in either format), its algorithm chosen, and the arguments missing from
# the call (pf(inner, ...)) are taken from that algorithm's settings
# (dev/ilike-language.md 4.7).
resolve_modules <- function(x)
{
  if (!is.list(x) || length(x) == 0)
    return(x)
  for (k in seq_along(x))
  {
    item = x[[k]]
    if (is.list(item) && is_module_placeholder(item$model))
      x[[k]] = resolve_algorithmic_likelihood(item)
    else if (is.list(item))
      x[[k]] = resolve_modules(item)
  }
  x
}

resolve_algorithmic_likelihood <- function(node)
{
  placeholder = node$model
  path = placeholder$path
  if (!grepl("^(/|[A-Za-z]:)", path))
    path = file.path(dirname(placeholder$importer), path)
  if (!file.exists(path))
    stop(paste(placeholder$importer, ": the imported file ", placeholder$path, " was not found (looked for ", path, ").", sep = ""),
         call. = FALSE)
  inner = compile(path)
  settings = list()
  if (identical(inner$language, "ilike"))
  {
    algorithm = if (is.null(placeholder$algorithm) || placeholder$algorithm == "") NULL else placeholder$algorithm
    prepared = prepare_recipe(inner, algorithm, list())
    inner = prepared$recipe
    settings = prepared$settings
  }
  node$model = inner

  # settings of the inner algorithm for the arguments not given in the call
  if (length(settings) > 0)
  {
    table = builtin_registry_table()
    entry = table[[node$type]]
    argument_names = names(entry$arguments)[-1] # (the first is the model)
    parameters = node$parameters
    if (is.null(parameters))
      parameters = list()
    keys = names(parameters)
    if (is.null(keys))
      keys = rep("", length(parameters))
    given = c(keys[keys != ""], argument_names[seq_len(sum(keys == ""))])
    for (a in setdiff(argument_names, given))
      for (key in names(settings))
        if (a %in% setting_aliases(key) || key == a)
          parameters[[a]] = settings[[key]]
    node$parameters = parameters
  }
  node
}

# --- functions in other languages (I5) -------------------------------------------

is_foreign_placeholder <- function(x)
{
  is.list(x) && !is.null(names(x)) && ("ilike_foreign" %in% names(x))
}

foreign_key <- function(p)
{
  paste(p$role, p$output, p$expression, sep = "\r")
}

collect_foreign_placeholders <- function(x, found = list())
{
  if (is_foreign_placeholder(x))
    return(c(found, list(x)))
  if (is.list(x))
    for (item in x)
      found = collect_foreign_placeholders(item, found)
  found
}

# the old format's group (block type) of a role, as extract_block needs it
foreign_block_type <- function(role)
{
  if (role == "data") return("data")
  if (role == "mcmc_weights") return("method")
  if (grepl("transition_proposal$", role)) return("transition_proposal")
  if (grepl("transition", role)) return("transition_model")
  for (p in c("unadjusted", "imh", "mh", "m", "is"))
    if (grepl(paste("_", p, "_proposal$", sep = ""), role))
      return(paste(p, "_proposal", sep = ""))
  "factor"
}

# Code in r, py and jl sections and imported files of those languages,
# loaded into R's global environment (where the generated wrappers find the
# functions), as the old format loads the files next to a recipe
load_foreign_code <- function(lowered, julia_bin_dir, julia_required_libraries)
{
  load = function(language, path)
  {
    if (language == "r")
      sys.source(path, envir = globalenv())
    else if (language == "py")
      reticulate::source_python(path, envir = globalenv())
    else
    {
      if (julia_bin_dir == "")
        stop("Julia binary directory needs to be specified to use Julia functions (julia_bin_dir).", call. = FALSE)
      JuliaCall::julia_setup(julia_bin_dir)
      list2env(my_julia_source(path, julia_required_libraries), .GlobalEnv)
    }
  }
  for (f in lowered$foreign_files)
  {
    path = f$path
    if (!grepl("^(/|[A-Za-z]:)", path))
      path = file.path(dirname(f$importer), path)
    if (!file.exists(path))
      stop(paste(f$importer, ": the imported file ", f$path, " was not found (looked for ", path, ").", sep = ""), call. = FALSE)
    load(f$language, path)
  }
  for (section in lowered$foreign_code)
  {
    path = tempfile(fileext = c(r = ".R", py = ".py", jl = ".jl")[[section$language]])
    writeLines(section$code, path)
    load(section$language, path)
  }
}

# A constant's name in an R expression replaced by its value
substitute_constants <- function(expression, constants, declared)
{
  used = intersect(all.vars(parse(text = expression)), declared)
  if (length(used) == 0)
    return(expression)
  missing = setdiff(used, names(constants))
  if (length(missing) > 0)
    stop(paste("The constant(s) ", paste(missing, collapse = ", "), " are used in a call to another language (",
               expression, "), so their values are needed when compiling: give them defaults in the constants section ",
               "or pass them to compile(model_parameter_list = list(...)).", sep = ""), call. = FALSE)
  call = do.call("substitute", list(parse(text = expression)[[1]], constants[used]))
  paste(deparse(call, width.cutoff = 500L), collapse = " ")
}

# The C++ wrapper of each function in another language: the old format's
# code for an R expression in the block of the same role (extract_block),
# which defines an R function calling it and a C++ function calling that.
generate_foreign_wrappers <- function(x, constants, declared, external_packages, julia_bin_dir, julia_required_libraries)
{
  code = character(0)
  getters = list()
  for (p in collect_foreign_placeholders(x))
  {
    key = foreign_key(p)
    if (!is.null(getters[[key]]))
      next
    expression = substitute_constants(p$expression, constants, declared)
    block_function = if (p$output != "") paste(p$output, "=", expression, sep = "") else expression
    # a number unique in the session: the generated R and C++ functions are
    # named by role and number
    .ilike_env$foreign_count = if (is.null(.ilike_env$foreign_count)) 1 else .ilike_env$foreign_count + 1
    number = 100000 + .ilike_env$foreign_count
    block_type = foreign_block_type(p$role)
    file_name = tempfile(fileext = ".cpp")
    connection = file(file_name, open = "w")
    blocks = tryCatch(
      extract_block(list(order_of_mcmc = c()), block_type, p$role, number, 0, "", block_function, FALSE, list(),
                    FALSE, external_packages, julia_bin_dir, julia_required_libraries, connection, FALSE, 1, FALSE, FALSE),
      error = function(e) {
        close(connection)
        message = sub("^Block [^,]*, line number [0-9]*: ", "", conditionMessage(e))
        stop(paste("The call ", expression, " (used as ", p$role, "): ", message, sep = ""), call. = FALSE)
      })
    close(connection)
    code = c(code, readLines(file_name))
    unlink(file_name)
    entry = blocks[[block_type]][[number]]
    getter = names(entry)[grepl("getXPtr", names(entry))][1]
    getters[[key]] = list(getter = getter, type = entry$type, cpp_name = paste(p$role, number, sep = ""))
  }

  # gradients by finite differences of a log density in another language
  # (gradient = autodiff, dev/plan.md 3.10): central differences, in C++
  # (ilike_finite_difference_gradient, in the generated code), of the C++
  # wrapper made above for the log density
  for (p in collect_finite_difference_placeholders(x))
  {
    key = finite_difference_key(p)
    if (!is.null(getters[[key]]))
      next
    log_name = getters[[foreign_key(p$log)]]$cpp_name
    log_signature = ilike_find_cpp_function_signature(paste(code, collapse = "\n"), log_name)
    log_arguments = c(if (grepl("Parameters", log_signature, fixed = TRUE)) "p",
                      if (grepl("Data", log_signature, fixed = TRUE)) "data")
    prior = identical(p$ilike_finite_difference, "prior")
    name = paste("ilike_finite_difference_", log_name, sep = "")
    arguments = paste("const std::string &variable, const Parameters &parameters", if (!prior) ", const Data &data", sep = "")
    code = c(code, "",
             paste("arma::mat ", name, "(", arguments, ")", sep = ""), "{",
             paste("  return ilike_finite_difference_gradient([&](const Parameters &p) { return (double)", log_name, "(",
                   paste(log_arguments, collapse = ", "), "); }, variable, parameters);", sep = ""), "}", "")
    pt = parameter_types_for_cpp(paste("arma::mat ", name, "(", arguments, ")", sep = ""))
    rt = return_types_for_cpp(p$role, 0, pt[[1]], pt[[2]], pt[[3]], pt[[4]])
    getter = paste(name, "getXPtr", sep = "_")
    code = c(code, "// [[Rcpp::export]]", paste("SEXP ", getter, "() {", sep = ""),
             paste("  typedef", rt[[1]], "(*funcPtr)(", rt[[2]], ");"),
             paste("  return XPtr<funcPtr>(new funcPtr(&", name, "));", sep = ""), "}", "")
    getters[[key]] = list(getter = getter, type = rt[[4]])
  }
  list(code = code, getters = getters)
}

is_finite_difference_placeholder <- function(x)
{
  is.list(x) && !is.null(names(x)) && ("ilike_finite_difference" %in% names(x))
}

finite_difference_key <- function(p)
{
  paste("finite_difference", p$role, foreign_key(p$log), sep = "\r")
}

collect_finite_difference_placeholders <- function(x, found = list())
{
  if (is_finite_difference_placeholder(x))
    return(c(found, list(x)))
  if (is.list(x))
    for (item in x)
      found = collect_finite_difference_placeholders(item, found)
  found
}
